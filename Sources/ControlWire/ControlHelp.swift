/// 命令の一覧と書式。アプリとコマンドの両方がこれを仕様の正本として使う。
public enum ControlHelp {
    public static let text = """
    hanectl — 起動中の Hane を外から操作する。アプリが起動していなければ自動で起動する。

    使い方: hanectl [--tab <番号>] <命令> [引数…]
      --tab を省くと、選択中のタブ（一覧で * の付いたタブ）が対象になる。

    タブ
      tabs                   タブの一覧。ページを持たないタブ（前回の閲覧から戻しただけのタブと、
                             しばらく画面に出さず眠らせたタブ）には [asleep] が付き、選ぶか reload すると
                             戻る・進むの履歴ごと起きる。サイトのアイコンを取れているタブには [icon] が付く
      new [URL|検索語]      新しいタブを開いて選択する
      select <番号>           タブを選択する
      close [番号]            タブを閉じる（最後の1枚は閉じられない）
      sleep [番号]            タブを眠らせてページのプロセスを返す（選択中のタブは眠らせられない）。
                             アプリは画面から外れて30分経ったタブを、選択が変わったときに自分で眠らせる

    ブックマーク（タブバーの左側に並ぶ。フォルダは一段だけ）
      bookmarks              番号つきの一覧。番号はフォルダも含めた上からの通し番号
                             ページを開いているものには (open: tab N)、選択中には * が付く
      bookmark-add [URL|検索語] [--name 名前] [--folder フォルダ名]
                             URLを省くと、今のタブをページごとブックマークへ移す
                             フォルダがなければ作る
      bookmark-open <番号>    ブックマークをその場で開く（ページがあれば切り替えるだけ）
      bookmark-remove <番号>  ブックマークかフォルダを消す。開いていたページはタブとして残る

    移動（どれも読み込みが終わり、ページの題名がアプリに届くまで待ってから返る）
      open <URL|検索語>       ページを開く。URLでなければ検索する
      back / forward / reload
      wait                   読み込みが終わるのを待つ
      wait [--text <文字列>] [--selector <CSSセレクタ>] [--js <式>] [--gone] [--timeout 秒] [--frame <フレーム>]
                             条件が成り立つまで待つ（読み込みのあとにスクリプトが描く画面向け）。
                             --text は本文にその文字列が現れるまで、--selector は合う見えている要素が現れるまで、
                             --js は式（await も書ける）が真になるまで。複数並べるとすべてが成り立つまで。
                             --gone は逆で、並べたどれも成り立たなくなる（消える）まで。
                             --timeout は既定 10 秒、最大 100 秒。時間切れは失敗で、最後に見えた状態を理由に出す。
                             待っている間にページが移れば、読み込みを待って移った先で続ける。
                             アラートのシートが出ると、ページのスクリプトが止まるので失敗にする（答えてから待ち直す）

    ダウンロード（アプリ全体で一つ。普段使いの実体はダウンロードフォルダ、使い捨ての実体は一時フォルダに保存する）
      downloads [--clear]    この実体で始まったダウンロードと保存先。--clear で終わったものを一覧から外す
                             download 属性のリンク、表示できない型、添付ファイルとして届いたものがダウンロードになる

    ページを読む
      snapshot [--limit N]   操作できる要素を番号つきで一覧する。見出しも併せて出る
                             iframe の中も（別のオリジンや入れ子も）、そのフレームの行（frame 1、frame 1.2 など。
                             iframe の名札とアドレス）の下に字下げして続く。番号はページ全体の通しで、どの命令でもそのまま使える。
                             フレームは主フレームの要素の後ろに、ページに並んだ順で出る
      text [--limit N] [--frame <フレーム>]
                             本文のテキスト。--frame 1.2 のように snapshot のフレームを指すと、その中の本文
      screenshot [保存先]     見えている範囲をPNGで保存し、パスを返す（選択中のタブのみ）
                             --full を付けるとページ全体を撮る
      eval [--frame <フレーム>] <JavaScript>
                             式の値、または return した値をJSONで返す。--frame で snapshot のフレームの中で走らせる
                             アラートのシートが出ている間はページのスクリプトが止まり、eval などページへの命令は返らない
                             （120 秒で落ちる）。先に ui-snapshot と ui-click か key return で答えること

    ページを操作する（番号は直前の snapshot のもの）
      click <番号>            クリックする
                             ページが alert / confirm / prompt を出すと窓のシートになり、答えるまでその命令は返らない。
                             別の hanectl から ui-snapshot と ui-click で答える
                             （裏のタブのページが出したものは、取り消したものとして答える）
                             ファイルの選択もシートで出るが、中身は別のプロセスが描くので拾えず、答えられない。
                             ui に overlay: sheet と出たままになったら quit で閉じる
      fill <番号> <文字列>     入力欄に文字列を入れる。select要素なら選択肢を選ぶ
      press <キー> [番号]      キーを送る（Enter, Escape, Tab, ArrowDown など）。Enter はフォームを送信する
                             番号を省くとフォーカスのある要素へ（iframe の中にフォーカスがあれば、その中の要素へ）
                             click / fill / press はページの中で作った事象で、ページからは isTrusted が false に見える

    ページへ本物の入力を渡す（利用者が操作したのと同じく isTrusted が true。選択中のタブのページだけ）
      page-click [--right] [--with <修飾>] <番号|x,y>
                             要素（snapshot の番号）の真ん中か、位置 x,y（CSS の画素。表示している範囲の左上から）を
                             押して離す。番号の要素が画面の外なら真ん中へスクロールしてから押す。
                             iframe の中の要素は、iframe の位置を足した位置で押す（結果に in frame 1 などと付く）
                             押した位置で事象を受ける要素を返す（ほかの要素に覆われていれば、手前のものを書く）
                             --right で右クリック、--with opt や --with cmd+shift で修飾キーを押しながら
                             例: page-click --right --with opt 5（⌥右クリックで、隠す要素を選び始める）
                             右クリックのメニューや選択欄の選択肢が出たら、すぐ閉じて項目を返す（選べない。選択欄は fill）
                             ポップアップを止めていても、操作の中からの window.open は開く
                             アプリが裏にいても届き、前には出ない
      page-hover <番号|x,y>  ポインタをそこへ動かす（ホバーで開くメニューなど）。
                             アプリが裏にいると WebKit がポインタの動きを捨てるので、前面にいるとき（HANE_LAUNCH=front）しか効かない。
                             なお page-click は裏でもその位置へポインタを移したことになり、ホバーの表示も変わる
      page-key <キー> [キー…]  キーを押して離す。並べると順に送る。文字のキーでの操作（j, G, g g, f など）が反応する。
                             キーは key と同じ書き方に、大文字（G は shift+g）と space を加えたもの
                             例: page-key j、page-key g g、page-key f → page-key s（印を選ぶ）、page-key escape
                             フォーカスをページへ移してから送る。⌘ 付きでもメニューには行かない（メニューは key）
                             アプリが裏にいても届き、前には出ない。結果はタブの一覧（x でタブが閉じるなど）

    プロファイル（Cookie、ブックマーク、閲覧履歴、閲覧状態を分けて持つ。窓一枚に一つずつ出す）
      profiles               プロファイルの一覧。今のもの（命令の相手。最後に前へ出たプロファイルの窓）に *、
                             ほかの窓に出ているものに + が付く
                             使い捨ての実体（dev など）では、登録した一覧は見せない
      profile-new <名前>      プロファイルを作る（開くのは profile-open）。使い捨ての実体ではその実体の中だけに作る
      profile-open <名前>     手前の窓をそのプロファイルへ移す。窓のタブは閲覧状態を書き出してから閉じ、移る先のタブを戻す
                             （選んでいたページだけ読み込む）。ほかの窓に出ていれば、その窓を前に出して今のものにする
                             アプリの中では ⌃1〜9 で、一覧の上から N 番目へ移る。⌘N（key cmd+n）で開いた窓では
                             プロファイルを選ぶ（ui-snapshot のボタンを ui-click）
                             普段使いの実体では持ち主のタブが閉じるので、頼まれていなければ聞いてから移ること
      activate               窓を前に出す（隠れていれば出す）。同じ実体を二重に起動したときに使う
      pid                    この実体のプロセス番号

    設定（メニューの「設定…」（⌘,）と同じもの。プロファイルによらずアプリ全体で一つ。普段使いの実体では保存される）
      settings               今の設定
      settings popups <block|allow>
                             ポップアップウインドウを止めるか。block では、クリックなどの操作の中から
                             window.open したものだけ開く。allow では操作がなくても開く
                             開いているタブにもその場で効く
                             大きさを指定したもの（ログインの小窓など）は別の小窓で開き、ui に overlay: window と出る。
                             ほかは新しいタブで開く

    広告ブロック（同梱のフィルタリストと、⌥右クリックで選んで隠した要素）
      adblock                フィルタリストの状態と、今のサイトで隠している要素。起動直後は準備を待ってから返る
      hide <CSSセレクタ>       今のページで合う要素を隠し、このサイトで次から隠すよう覚える
                             ⌥右クリックで選んで「隠す」を押したのと同じ
      unhide                 今のサイトで隠した要素をすべて戻し、読み込み直す
                             フィルタリストで止めた読み込みは requests の not loaded で見る

    開発と調査
      ui                     ウインドウの枠まわりの状態（窓の大きさと位置、アドレスバー、ボタン、
                             ブックマークとタブの並び）。窓の位置は画面の左上から測る
                             フォルダの一覧が出ていれば folder list に行が並び、選択中の行に > が付く
      window-screenshot [保存先]
                             窓の中身（タブバー、ナビゲーションの段、ページ）をPNGで保存し、パスと外観を返す。
                             アプリが自分で描くので、画面収録の権限が要らず、窓が裏にいても撮れる。
                             窓の枠と信号機ボタンは写らない
      key <キー>              ページの外（メニューやバー）へキーを送り、ui の結果を返す
                             キーは 1〜9, a〜z, up, down, left, right, return, escape, delete, tab, space, ","。
                             cmd+ ctrl+ opt+ shift+ を前に付けられる
                             例: key cmd+1（バーの左から1番目。フォルダなら一覧を開く）、key ctrl+tab（次のタブ）、
                             key cmd+,（設定の窓を開く）、key cmd+w（タブか、手前の設定の窓を閉じる）
                             アプリが裏にいても届き、前には出ない
                             ページにフォーカスがあると修飾なしのキーはページにも届く（押して離すのを対で送る）。
                             ページへ送るのが目的なら page-key を使うこと
      type [--replace] <文字列>
                             フォーカスのある入力欄（アドレスバーなど）へ1文字ずつ打ち込み、ui の結果を返す
                             入力方式に左右されない。--replace を付けると今の中身を選んでから打つ（置き換える）
                             履歴から補った続きは ui の completion に出る
                             例: new → type git → key return（補ったページへ移る）
      ui-snapshot            窓まわりの部品（タブ、ブックマーク、ボタン、入力欄）を番号つきで一覧する。
                             ポップオーバーやシート（アラート）が出ていれば、その中身も続けて出る。
                             設定の窓のように別に開いた窓も、本体の窓より手前にあれば続けて出る（位置はその窓の左上から。
                             中身は window-screenshot には写らない）。
                             位置は窓の左上から測るので、window-screenshot の画像と突き合わせられる
      ui-click <番号>         部品の真ん中をクリックし、ui の結果を返す（番号は直前の ui-snapshot のもの）
                             アプリが裏にいても届き、前には出ない
      ui-hover <番号>         ポインタを部品の上へ動かす。乗せたときだけ出る部品（タブの閉じるボタンなど）を出す
      ui-menu <番号> [項目]   部品の右クリックのメニューを一覧する。選択欄（popup）ならその選択肢を一覧する。
                             項目（番号か名前）を付けると、それを選ぶ。メニューは画面には出さない
                             例: ui-menu 2 → ui-menu 2 名前とフォルダを編集…（編集のポップオーバーが出る）
      window-size <幅> <高さ>  窓の大きさを変える（左上は動かさない）。幅で見た目が変わる部品を確かめるため
      appearance [dark|light|system]
                             このアプリの外観を固定する。system でシステムに従う。引数なしで今の外観を返す
      history [--limit N]    閲覧履歴を新しい順に。typed はアドレスバーで確定して訪れた回数
      logs [--limit N] [--clear]
                             console出力、未処理の例外、読み込み失敗の記録（新しい順ではなく時系列）
      app-logs [--limit N] [--seconds N]
                             アプリ自身の記録（保存の失敗、起動のとりやめ、操作用ソケットを開けなかったことなど）を、
                             時系列で最後の N 件（既定 50）。--seconds N で直近 N 秒に絞る。このプロセスが出した分だけで、
                             アプリを起こし直すと前の分は読めない。読むのに 1 秒近くかかる。ページの記録は logs
      requests [--limit N] [--url <部分一致>] [--type <種類,…>] [--json]
                             ページが読み込んだもの（ページ本体、スクリプト、画像、fetch など）を、フレームごとに始まった順で。
                             列は、主フレームのページを開き始めてからの時刻、かかった時間、運んだ大きさ、種類、URL。
                             大きさの cache はキャッシュから読んだもの、- は分からないもの（別のオリジンなど）
                             iframe は見えていないものも辿り、snapshot と同じ番号（frame 1.2）か、見えていなければ frame h1 と出る。
                             種類は script, img, link, css, fetch, xmlhttprequest, iframe, navigation など（--type script,img で絞る）
                             最後の not loaded に、要素（script, img, link, iframe）が指しているのに読み込んだ記録がないものが出る。
                             広告ブロックで止められたものはここに出る（つながらなかったもの、まだ読み込み中のものも混じる）。
                             スクリプトが fetch などで頼んで止められたものは、どこにも出ない
                             記録はページが自分で持っているもの（Resource Timing）を読むだけで、file: の資源は記録されない。
                             一つの文書で 250 件を超えると、その後の読み込みは記録されない（そう書き添える）
      stats [--seconds N] [--json]
                             アプリと補助プロセスのメモリ、CPU、起床回数（wakeups/s）。
                             CPUと起床回数は N 秒間（既定 0.5、最大 60）の平均。何もしていない
                             ときの起床回数が増えていれば、常に何かが動いている。--json で機械向けに出す
                             ページのプロセス（WebContent）の行の右端に、そのプロセスが描いているタブの番号が出る
                             （--json では tabs）。番号のないページのプロセスは、どのタブにも結びついていない
                             最後の行に測った実行ファイルが出るので、入れてある版と取り違えていないか確かめること
      quit                   アプリを終了する。受けた時点で次の命令を受けなくなるので、続けて送った命令は新しい実体が受ける

    環境変数
      HANE_INSTANCE=<名前>    普段使いとは別の実体を相手にする。ソケットが別になり、Cookie なども保存しない使い捨てになる。
                             開発や検証では dev を使うこと。起動していなければ、隣の build/Hane.app を裏で起こす（前には出ない）
                             （前の BROWSER_INSTANCE、BROWSER_PROFILE、BROWSER_EPHEMERAL は使えない。付いていると止まる）
      HANE_LAUNCH=front      自動で起こすとき前に出す。乗せたときだけ出る表示（ui-hover）は前面でしか確かめられない

    典型的な流れ
      hanectl open example.com
      hanectl snapshot          # → [3] textbox "検索" などが並ぶ
      hanectl fill 3 "swift"
      hanectl press Enter 3
      hanectl text

    注意
      ・ページが変わったら番号は無効になる。操作の前に snapshot を取り直すこと。
      ・iframe の中を読めないフレームは、snapshot のフレームの行にわけが付く。
        読み込めず中身のない iframe（つながらなかったものなど）と、見えていない iframe は出ない。
      ・iframe を x,y の位置で page-click すると、押すことはできるが、返す要素は iframe そのものになる。
      ・窓まわりのドラッグ（タブやブックマークの並べ替え）はできない。作ったマウスの事象ではドラッグが始まらない。
      ・失敗したときは終了コード1で、理由を標準エラーに出す。
    """
}
